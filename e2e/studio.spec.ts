import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('generate six variants, edit, undo, palette and export', async ({page}) => {
  const errors:string[]=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('img',{name:'Холст композиции'})).toBeVisible();
  await page.getByRole('button',{name:'Создать композицию',exact:false}).click();
  await page.getByRole('button',{name:'По теме',exact:true}).click();
  await page.getByLabel('О чём ваша иллюстрация?').fill('Обучение и развитие');
  await page.getByRole('button',{name:'6 вариантов',exact:true}).click();
  await page.getByRole('button',{name:'Сгенерировать',exact:false}).click();
  await expect(page.locator('.variant-card')).toHaveCount(6);
  const canvas=page.getByRole('img',{name:'Холст композиции'});
  await page.locator('.layer-select').first().click();
  await page.getByRole('button',{name:'Дублировать объект'}).click();
  const before=await page.locator('.layer-item').count();
  await page.getByRole('button',{name:'Удалить объект',exact:true}).click();
  await expect(page.locator('.layer-item')).toHaveCount(before-1);
  await page.getByRole('button',{name:'Отменить',exact:true}).click();
  await expect(page.locator('.layer-item')).toHaveCount(before);
  const initialBox = (await canvas.boundingBox())!;
  await page.getByRole('button',{name:'Увеличить масштаб',exact:true}).click();
  const zoomedBox = (await canvas.boundingBox())!;
  expect(zoomedBox.width).toBeGreaterThan(initialBox.width);
  await page.getByRole('button',{name:'Перемещение холста',exact:true}).click();
  const viewport = (await page.locator('.canvas-viewport').boundingBox())!;
  await page.mouse.move(viewport.x+viewport.width/2,viewport.y+viewport.height/2);
  await page.mouse.down(); await page.mouse.move(viewport.x+viewport.width/2+20,viewport.y+viewport.height/2+15,{steps:3}); await page.mouse.up();
  expect((await canvas.boundingBox())!.x).toBeGreaterThan(zoomedBox.x);
  await page.getByRole('button',{name:'Вписать холст',exact:true}).click();
  await page.getByRole('button',{name:'Mint',exact:true}).click();
  await expect(canvas).toHaveCSS('background-color','rgb(237, 245, 241)');
  await page.getByRole('button',{name:'Story',exact:false}).click();
  await expect(canvas).toHaveAttribute('viewBox','0 0 1080 1920');
  await page.getByRole('button',{name:'Экспорт',exact:true}).click();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Векторный SVG',exact:false}).click();
  const svgDownload = await download;
  expect(svgDownload.suggestedFilename()).toBe('forma-composition.svg');
  const exported = await readFile((await svgDownload.path())!, 'utf8');
  expect(exported).toContain('viewBox="0 0 1080 1920"');
  expect(exported).not.toMatch(/<(image|canvas|script)|base64|file:\/\//i);
  expect(errors).toEqual([]);
});

test('imports original SVG, configures tags, saves to Python and restores JSON',async({page})=>{
  await page.goto('/');
  const svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 100"><rect width="200" height="100" fill="#123456"/></svg>';
  await page.locator('.library-footer input[type=file]').setInputFiles({name:'Оригинал.svg',mimeType:'image/svg+xml',buffer:Buffer.from(svg)});
  await expect(page.getByRole('button',{name:'Выбрать Оригинал',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Добавить Оригинал на холст'}).click();
  const originalX = await page.getByLabel('X, %', {exact:true}).inputValue();
  const object = page.locator('.canvas-element').last();
  const box = (await object.boundingBox())!;
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down(); await page.mouse.move(box.x+box.width/2+25,box.y+box.height/2+20,{steps:5}); await page.mouse.up();
  expect(await page.getByLabel('X, %', {exact:true}).inputValue()).not.toBe(originalX);
  await page.getByRole('button',{name:'Отменить',exact:true}).click();
  await page.getByRole('button',{name:'Настроить Оригинал'}).click();
  await page.getByLabel('Теги для подбора по теме').fill('книга, обучение');
  await page.getByRole('button',{name:'Сохранить настройки'}).click();
  await page.getByLabel('Название проекта').fill('E2E проект');
  await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('сохранён на сервере');
  await page.getByRole('button',{name:'Сохранённые проекты',exact:true}).click();
  await expect(page.getByRole('button',{name:'E2E проект',exact:false})).toBeVisible();
  await page.getByRole('button',{name:'E2E проект',exact:false}).click();
  await expect(page.getByLabel('Название проекта')).toHaveValue('E2E проект');
  await page.getByRole('button',{name:'Экспорт',exact:true}).click();
  const jsonDownload = page.waitForEvent('download');
  await page.getByRole('button',{name:'Проект JSON',exact:false}).click();
  const projectPath = (await (await jsonDownload).path())!;
  await page.getByRole('button',{name:'Очистить холст'}).click();
  await expect(page.locator('.canvas-element')).toHaveCount(0);
  await page.locator('.studio-app > input[type=file]').setInputFiles(projectPath);
  await expect(page.getByRole('status')).toContainText('Проект открыт');
  expect(await page.locator('.canvas-element').count()).toBeGreaterThan(0);
  await page.reload();
  await expect(page.getByRole('button',{name:'Выбрать Оригинал',exact:true})).toBeVisible();
});

